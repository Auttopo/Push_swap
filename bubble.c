#include "push_swap.h"

void    bubble(t_stack **s1, int size)
{
    int i;

    i = 0;
    while (i <= size)
    {
        i++;
        if ((*s1)->value > (*s1)->next->value)
        {
            swap(s1);
            i = 0;
        }
        rotate(s1);
    }
        
}
